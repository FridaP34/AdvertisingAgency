/**
 * Renders every page of a booklet PDF to WebP, for the in-page reader.
 *
 * The brochure page shows its pages one under another, as a booklet is read,
 * scroll by scroll. A browser PDF frame depends on a built-in reader that is
 * often missing (or blocked) in a filtered environment, so the pages are
 * rendered here once and served as plain pictures.
 *
 *   public/works/<slug>/pages/page-01.webp …
 *
 * Usage: node tools/render-brochure-pages.mjs [slug …]   (no slug = every PDF)
 */
import fs from "node:fs";
import path from "node:path";
import mupdf from "mupdf";
import sharp from "sharp";

const WORKS_DIR = path.resolve("public/works");
const PAGE_W = Number(process.env.PAGE_W ?? 900);

const wanted = process.argv.slice(2);
const slugs = fs
  .readdirSync(WORKS_DIR)
  .filter((slug) => fs.existsSync(path.join(WORKS_DIR, slug, "presentation.pdf")))
  .filter((slug) => wanted.length === 0 || wanted.includes(slug));

/** Wider pages are capped at PAGE_W; taller-than-wide ones get the same width. */
async function pageBuffer(pixmap) {
  return sharp(pixmap.asPNG())
    .resize({ width: PAGE_W, withoutEnlargement: true })
    .webp({ quality: 82 })
    .toBuffer();
}

for (const slug of slugs) {
  const src = path.join(WORKS_DIR, slug, "presentation.pdf");
  const outDir = path.join(WORKS_DIR, slug, "pages");
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  const doc = mupdf.Document.openDocument(fs.readFileSync(src), "application/pdf");
  const count = doc.countPages();
  const sizes = [];

  for (let i = 0; i < count; i += 1) {
    const page = doc.loadPage(i);
    const [x0, y0, x1, y1] = page.getBounds();
    const longest = Math.max(x1 - x0, y1 - y0);
    // Render at a little over the served width, so text stays crisp at 1×.
    const scale = (PAGE_W * 1.35) / longest;
    const pixmap = page.toPixmap(
      mupdf.Matrix.scale(scale, scale),
      mupdf.ColorSpace.DeviceRGB,
      false,
      true,
    );
    const buffer = await pageBuffer(pixmap);
    const name = `page-${String(i + 1).padStart(2, "0")}.webp`;
    fs.writeFileSync(path.join(outDir, name), buffer);
    const meta = await sharp(buffer).metadata();
    sizes.push({ width: meta.width, height: meta.height });
  }

  const total = fs
    .readdirSync(outDir)
    .reduce((sum, file) => sum + fs.statSync(path.join(outDir, file)).size, 0);
  console.log(`${slug}: ${count} pages, ${Math.round(total / 1024)} KB total`);
}

/* ── The manifest the reader lays the pages out with ─────────────────────── */

const manifestPath = path.resolve("src/lib/works/booklet-pages/index.ts");
const entries = [];
for (const slug of fs.readdirSync(WORKS_DIR).sort()) {
  const dir = path.join(WORKS_DIR, slug, "pages");
  if (!fs.existsSync(dir)) continue;
  const sizes = [];
  for (const file of fs.readdirSync(dir).sort()) {
    const meta = await sharp(path.join(dir, file)).metadata();
    sizes.push(`{ width: ${meta.width}, height: ${meta.height} }`);
  }
  entries.push(`  "${slug}": [${sizes.join(", ")}],`);
}

fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
fs.writeFileSync(
  manifestPath,
  `/**
 * The rendered pages of each booklet — one entry per page, in order.
 *
 * Generated by \`tools/render-brochure-pages.mjs\`. Do not edit by hand; run
 * the tool again when a booklet file changes.
 */
export const bookletPages: Record<string, { width: number; height: number }[]> = {
${entries.join("\n")}
};
`,
);
console.log(`manifest: ${entries.length} booklets → ${path.relative(process.cwd(), manifestPath)}`);
