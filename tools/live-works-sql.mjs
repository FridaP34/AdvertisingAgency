/**
 * Builds `tools/tmp-live-works.sql` — the two statements that copy the demo's
 * catalogue (works and their assets) into the live project.
 *
 *   node tools/live-works-sql.mjs
 *
 * Then run it once in Supabase → SQL Editor → New query → Run. The SQL Editor
 * talks to the database directly, from inside Supabase, so it is not affected
 * by the network problem that makes PostgREST reject inserts from this machine
 * (21000 "UPDATE requires a WHERE clause").
 *
 * The values are inlined with literal quoting, not parameters, because that is
 * what can be pasted into the editor. Strings are doubled for `'` and written
 * as E'…' so the Hebrew and any backslash are read exactly as they are.
 *
 * Re-running is safe: a work is matched by slug, and its assets are replaced
 * as a set, exactly as the admin area saves them.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import pg from "pg";

const DEMO_PG = process.env.DEMO_PG ?? "postgres://postgres:postgres@127.0.0.1:54329/postgres";
const LIVE_URL = (process.env.LIVE_SUPABASE_URL ?? "https://etqugojfewwpediksczs.supabase.co").replace(/\/+$/, "");
const OUT = path.join(process.cwd(), "tools", "tmp-live-works.sql");
const BUCKET = "works";

/** A SQL string literal: E'…' with `'` and `\` escaped. */
const lit = (value) =>
  value === null || value === undefined
    ? "null"
    : `E'${String(value).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;

const int = (value) => (value === null || value === undefined ? "null" : String(Number(value)));

const demo = new pg.Client({ connectionString: DEMO_PG });
await demo.connect();

const works = (
  await demo.query(
    `select slug, title, client, category, work_type, summary, story, year, published, display_order
     from public.works order by display_order`,
  )
).rows;

const assets = (
  await demo.query(
    `select w.slug, a.url, a.asset_type, a.caption, a.width, a.height, a.display_order
     from public.works_assets a join public.works w on w.id = a.work_id
     order by w.display_order, a.display_order, a.id`,
  )
).rows;
await demo.end();

// The demo's URLs point at the local Storage host; only the object path matters.
const marker = `/storage/v1/object/public/${BUCKET}/`;
const liveUrl = (url) => {
  const at = url.indexOf(marker);
  return at === -1 ? url : `${LIVE_URL}${marker}${url.slice(at + marker.length)}`;
};

const workValues = works
  .map(
    (w) =>
      `  (${lit(w.slug)}, ${lit(w.title)}, ${lit(w.client ?? "")}, ${lit(w.category)}, ${lit(w.work_type)}, ` +
      `${lit(w.summary ?? "")}, ${lit(w.story)}, ${lit(w.year)}, ${w.published ? "true" : "false"}, ${int(w.display_order)})`,
  )
  .join(",\n");

const assetValues = assets
  .map(
    (a) =>
      `  (${lit(a.slug)}, ${lit(liveUrl(a.url))}, ${lit(a.asset_type)}, ${lit(a.caption)}, ` +
      `${int(a.width)}, ${int(a.height)}, ${int(a.display_order)})`,
  )
  .join(",\n");

const slugs = works.map((w) => lit(w.slug)).join(", ");

const sql = `-- Mindy Plavinsky — copy the catalogue into the live project.
-- Generated by tools/live-works-sql.mjs; run once in the SQL Editor.
-- Safe to run again: works are matched by slug, assets are replaced as a set.

begin;

insert into public.works
  (slug, title, client, category, work_type, summary, story, year, published, display_order)
values
${workValues}
on conflict (slug) do update set
  title         = excluded.title,
  client        = excluded.client,
  category      = excluded.category,
  work_type     = excluded.work_type,
  summary       = excluded.summary,
  story         = excluded.story,
  year          = excluded.year,
  published     = excluded.published,
  display_order = excluded.display_order,
  updated_at    = now();

delete from public.works_assets
 where work_id in (select id from public.works where slug in (${slugs}));

insert into public.works_assets (work_id, url, asset_type, caption, width, height, display_order)
select
  w.id,
  v.url, v.asset_type, v.caption, v.width, v.height, v.display_order
from (
values
${assetValues}
) as v (work_slug_ref, url, asset_type, caption, width, height, display_order)
join public.works w on w.slug = v.work_slug_ref;

commit;

select
  (select count(*) from public.works)       as works,
  (select count(*) from public.works where published) as published,
  (select count(*) from public.works_assets) as assets;
`;

writeFileSync(OUT, sql, "utf8");
const bytes = readFileSync(OUT).length;
console.log(`נכתב ${path.relative(process.cwd(), OUT)} — ${works.length} עבודות, ${assets.length} רשומות קבצים, ${Math.round(bytes / 1024)} ק"ב.`);
